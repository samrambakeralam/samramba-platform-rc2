/*************************************************
 PUBLIC ACCESS HELPER
*************************************************/

window.SamrambaBookContent = {

    getVersion: function(versionId) {

        return (
            window.SAMRAMBA_BOOK_CONTENT[versionId] ||
            null
        );

    },

    getPage: function(versionId, pageNumber) {

        const version =
            this.getVersion(versionId);

        if (!version) {
            return null;
        }

        return (
            version.pages.find(function(page) {
                return page.page === pageNumber;
            }) || null
        );

    },

    getPageCount: function(versionId) {

        const version =
            this.getVersion(versionId);

        if (!version) {
            return 0;
        }

        return version.pages.length;

    }

};